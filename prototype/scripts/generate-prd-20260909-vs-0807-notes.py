def emit_docx(mod, md: Path, meta: dict):
    rows = parse_rows(md.read_text(encoding="utf-8"))
    out = md.with_suffix(".docx")
    if out.exists():
        out.unlink()
    mod.write_change_note_docx(md, out, meta, rows)
    return len(rows)


