def write_change_note(m: dict, ver_path: Path):
    prev = m.get("prev")
    if prev:
        stem = f"{m['cn']}{prev[0]}{prev[1]}→{DATE}{m['ver']}变更说明"
        from_label = f"{prev[1]}"
        from_file = f"{m['cn']}{prev[0]}{prev[1]}.docx"
    else:
        stem = f"{m['cn']}无→{DATE}{m['ver']}变更说明"
        from_label = "无"
        from_file = "—"
    md_out = ver_path / f"{stem}.md"
    docx_out = ver_path / f"{stem}.docx"
    ensure_writable(md_out)
    ensure_writable(docx_out)

    # 覆盖重跑：补充一条模板纠偏说明（若尚未有 V3.1 字样）
    rows = list(m["changes"])
    if not any("V3.1" in r.get("content", "") for r in rows):
        rows.insert(
            0,
            {
                "obj_type": "其他",
                "obj_id": "—",
                "where": "文档结构",
                "type": "修改",
                "content": f"正文按 {TEMPLATE_NAME} 重写（覆盖同版本产出）",
                "status": "已明确",
            },
        )

    lines = [
        f"# {m['cn']}——需求调整变更说明",
        "",
        "> 模板：`参考文档/0、模板/需求调整变更说明模板（简版）20260901V3.docx`  ",
        f"> 对照：{from_label} → {m['ver']}",
        "",
        "## 1 版本信息",
        "",
        "| 项目 | 内容 |",
        "|------|------|",
        f"| 需求文档名称 | 厦大马来分校本科教务系统产品需求文档 — {m['cn']} |",
        f"| 菜单路径 | {m['path']} |",
        f"| 上一有效版 → 本版 | {from_label} → {m['ver']} |",
        f"| 上一版文件 | {from_file} |",
        f"| 本版文件 | {m['cn']}{DATE}{m['ver']}.docx |",
        f"| 本版 PRD 模板 | {TEMPLATE_LABEL} |",
        f"| 变更日期 | {CHANGE_DATE} |",
        "",
        "## 2 本次改了什么（总览）",
        "",
        "| 序号 | 模块（菜单路径） | 对象类型 | 对象ID | 功能 / 位置（可读名） | 变更类型 | 调整内容（从什么变成什么） | 状态 |",
        "|------|------------------|----------|--------|---------------------|----------|------------------------------|------|",
    ]
    for i, r in enumerate(rows, 1):
        lines.append(
            f"| {i} | {m['path']} | {r['obj_type']} | {r['obj_id']} | {r['where']} | "
            f"{r['type']} | {r['content']} | {r['status']} |"
        )
    lines += [
        "",
        "## 3 前后对照（可选）",
        "",
        "总览已能说明的条目不展开。",
        "",
        "## 4 连带影响（可选）",
        "",
        "| 序号 | 影响到哪里 | 影响说明 | 需同步 |",
        "|------|------------|----------|--------|",
        f"| 1 | 原型 / 文档 | 以现行原型为准整理为 PRD {TEMPLATE_LABEL} | ☑原型 □开发 □测试 |",
        "",
    ]
    md_out.write_text("\n".join(lines), encoding="utf-8")

    template = ROOT / "参考文档" / "0、模板" / "需求调整变更说明模板（简版）20260901V3.docx"
    doc = Document(str(template))
    t0 = doc.tables[0]
    kv = {
        "需求文档名称": f"厦大马来分校本科教务系统产品需求文档 — {m['cn']}",
        "菜单路径": m["path"],
        "上一有效版": f"{from_label} → {m['ver']}",
        "上一版文件": from_file,
        "本版文件": f"{m['cn']}{DATE}{m['ver']}.docx",
        "本版 PRD 模板": TEMPLATE_LABEL,
        "原型地址": "—（V3.1 正文不写原型地址；对照见 PRD 第 10 章）",
        "变更日期": CHANGE_DATE,
    }
    for row in t0.rows:
        label = (row.cells[0].text or "").strip()
        for k, v in kv.items():
            if k in label:
                row.cells[1].text = ""
                run = row.cells[1].paragraphs[0].add_run(v)
                set_run_cn(run)
                break
    t1 = doc.tables[1]
    for i, row in enumerate(t1.rows[1:]):
        if i >= len(rows):
            for c in row.cells:
                c.text = ""
            continue
        r = rows[i]
        vals = [str(i + 1), m["path"], r["obj_type"], r["obj_id"], r["where"], r["type"], r["content"], r["status"]]
        for cell, val in zip(row.cells, vals):
            cell.text = ""
            run = cell.paragraphs[0].add_run(val)
            set_run_cn(run, size=9)
    doc.save(docx_out)
    return md_out, docx_out


def main():
    only = parse_only_menus()
    written = []
    for m in MENUS:
        if only is not None and m["cn"] not in only:
            continue
        ver_path = version_dir(m["cn"], DATE, m["ver"])
        if ver_path.exists() and not ALLOW_OVERWRITE:
            raise SystemExit(f"拒绝覆盖已有版本目录：{ver_path}（加 --allow-overwrite 可覆盖）")
        ver_path.mkdir(parents=True, exist_ok=True)
        md = ver_path / f"{m['cn']}{DATE}{m['ver']}.md"
        docx = ver_path / f"{m['cn']}{DATE}{m['ver']}.docx"
        write_md(m, md)
        write_docx_from_md_structure(m, docx)
        ch_md, ch_docx = write_change_note(m, ver_path)
        written.append((m["cn"], m["ver"], ver_path))
        print(f"OK {m['cn']} {m['ver']} → {ver_path.relative_to(ROOT)}")

    if only is not None and not written:
        raise SystemExit(f"--only 未匹配到菜单：{only}")
    print(f"\nTotal menus: {len(written)}  overwrite={ALLOW_OVERWRITE} template={TEMPLATE_LABEL}")
    for cn, ver, vp in written:
        print(f"  - {cn} {ver}: {vp}")


if __name__ == "__main__":
    main()
