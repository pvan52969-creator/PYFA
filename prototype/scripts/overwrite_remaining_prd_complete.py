def set_run_font(run, size=10.5, bold=False, highlight=False):
    run.font.name = ASCII
    run._element.rPr.rFonts.set(qn("w:ascii"), ASCII)
    run._element.rPr.rFonts.set(qn("w:hAnsi"), ASCII)
    run._element.rPr.rFonts.set(qn("w:eastAsia"), EAST)
    run.font.size = Pt(size)
    run.bold = bold
    if highlight:
        rPr = run._element.get_or_add_rPr()
        for old in rPr.findall(qn("w:highlight")):
            rPr.remove(old)
        hl = OxmlElement("w:highlight")
        hl.set(qn("w:val"), "yellow")
        rPr.append(hl)


def add_para(doc, text, *, size=10.5, bold=False, highlight=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, highlight=highlight)
    return p


def should_hl(text: str) -> bool:
    keys = (
        "完整重写", "P01-X01", "P01-M02", "P02-", "FD03", "FD04", "FD05", "FD06",
        "BR010", "BR011", "BR012", "BR013", "BR014", "多选下拉", "一键分配",
        "modal-otr", "Combined Groups", "No. of Groups", "特殊开课",
    )
    return any(k in text for k in keys)


def parse_blocks(md: str):
    lines = md.splitlines()
    blocks, i = [], 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("#"):
            level = len(line) - len(line.lstrip("#"))
            blocks.append(("h", level, line.lstrip("#").strip()))
            i += 1
            continue
        if line.startswith("```"):
            buf = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                buf.append(lines[i])
                i += 1
            i += 1
            blocks.append(("code", "\n".join(buf)))
            continue
        if line.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s\-:|]+\|$", lines[i + 1].strip()):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                if re.match(r"^\|[\s\-:|]+\|$", lines[i].strip()):
                    i += 1
                    continue
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                rows.append(cells)
                i += 1
            blocks.append(("table", rows))
            continue
        if line.strip().startswith(">"):
            blocks.append(("quote", line.strip().lstrip("> ").strip()))
            i += 1
            continue
        if line.strip():
            blocks.append(("p", line.strip()))
        i += 1
    return blocks


def add_table(doc, rows):
    if not rows:
        return
    cols = max(len(r) for r in rows)

    def trim(r):
        if len(r) <= 10:
            return r + [""] * (10 - len(r)) if cols > 10 else r
        return r[:9] + [r[-1]]

    if cols > 10:
        rows = [trim(r) for r in rows]
        cols = 10
    table = doc.add_table(rows=len(rows), cols=cols)
    table.style = "Table Grid"
    for ri, row in enumerate(rows):
        hl = ri > 0 and should_hl("|".join(row))
        for ci in range(cols):
            cell = table.rows[ri].cells[ci]
            text = row[ci] if ci < len(row) else ""
            cell.text = ""
            p = cell.paragraphs[0]
            run = p.add_run(text)
            set_run_font(run, size=9, bold=(ri == 0), highlight=hl)
            if ri == 0:
                shading = OxmlElement("w:shd")
                shading.set(qn("w:fill"), "D9E2F3")
                shading.set(qn("w:val"), "clear")
                cell._tc.get_or_add_tcPr().append(shading)


def build_docx(md_text: str, out: Path, title: str):
    doc = Document()
    for s in doc.sections:
        s.top_margin = Cm(1.5)
        s.bottom_margin = Cm(1.5)
        s.left_margin = Cm(1.5)
        s.right_margin = Cm(1.5)
    add_para(doc, title, size=16, bold=True)
    add_para(doc, "文档版本：20260902V2　　完整重写覆盖：2026-09-03　　模板：PRD V3.1", size=9, highlight=True)
    for b in parse_blocks(md_text):
        if b[0] == "h":
            _, level, title_h = b
            if title_h.startswith("厦大马来"):
                continue
            add_para(doc, title_h, size=14 if level <= 2 else 12, bold=True, highlight=should_hl(title_h))
        elif b[0] == "quote":
            add_para(doc, b[1], size=9, highlight=should_hl(b[1]))
        elif b[0] == "code":
            add_para(doc, b[1], size=9, highlight=True)
        elif b[0] == "p":
            add_para(doc, b[1], size=10.5, highlight=should_hl(b[1]))
        elif b[0] == "table":
            add_table(doc, b[1])
            doc.add_paragraph()
    doc.save(str(out))


