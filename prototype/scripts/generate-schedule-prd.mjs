function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function p(text, { bold = false, size = 21 } = {}) {
  const runProps = `<w:rPr><w:rFonts w:ascii="宋体" w:hAnsi="宋体" w:eastAsia="宋体" w:cs="宋体"/>${bold ? '<w:b/><w:bCs/>' : ''}<w:sz w:val="${size}"/><w:szCs w:val="${size}"/></w:rPr>`;
  return `<w:p><w:r>${runProps}<w:t xml:space="preserve">${esc(text)}</w:t></w:r></w:p>`;
}

function h(text, level = 1) {
  // 与培养方案正式版一致：Title=0，Heading1~4
  const style = level <= 0 ? 'Title' : `Heading${Math.min(level, 4)}`;
  const size = level <= 0 ? 36 : level === 1 ? 32 : level === 2 ? 28 : level === 3 ? 24 : 22;
  return `<w:p><w:pPr><w:pStyle w:val="${style}"/></w:pPr><w:r><w:rPr><w:rFonts w:ascii="黑体" w:hAnsi="黑体" w:eastAsia="黑体"/><w:b/><w:sz w:val="${size}"/><w:szCs w:val="${size}"/></w:rPr><w:t>${esc(text)}</w:t></w:r></w:p>`;
}

function cell(text, { bold = false, center = false, width = 0 } = {}) {
  const jc = center ? '<w:jc w:val="center"/>' : '';
  const tcW = width ? `<w:tcW w:w="${width}" w:type="dxa"/>` : '<w:tcW w:w="0" w:type="auto"/>';
  // 支持单元格内换行
  const paras = String(text ?? '').split('\n').map(line =>
    `<w:p><w:pPr>${jc}</w:pPr><w:r><w:rPr><w:rFonts w:ascii="宋体" w:hAnsi="宋体" w:eastAsia="宋体"/>${bold ? '<w:b/>' : ''}<w:sz w:val="18"/><w:szCs w:val="18"/></w:rPr><w:t xml:space="preserve">${esc(line)}</w:t></w:r></w:p>`
  ).join('');
  return `<w:tc><w:tcPr>${tcW}</w:tcPr>${paras || '<w:p/>'}</w:tc>`;
}

function table(headers, rows, { header = true } = {}) {
  const border = 'w:val="single" w:sz="4" w:space="0" w:color="000000"';
  const tblBorders = `<w:tblBorders><w:top ${border}/><w:left ${border}/><w:bottom ${border}/><w:right ${border}/><w:insideH ${border}/><w:insideV ${border}/></w:tblBorders>`;
  const hdr = header && headers?.length
    ? `<w:tr>${headers.map(hh => cell(hh, { bold: true, center: true })).join('')}</w:tr>`
    : '';
  const body = rows.map(r => `<w:tr>${r.map((c, i) => cell(c, { bold: !header && i === 0 })).join('')}</w:tr>`).join('');
  return `<w:tbl><w:tblPr>${tblBorders}<w:tblW w:w="0" w:type="auto"/><w:tblLayout w:type="autofit"/></w:tblPr>${hdr}${body}</w:tbl>${p('')}`;
}

/** 与培养方案正式版 add_kv_table 一致：无表头两列表，左列加粗 */
function kv(rows) {
  return table(null, rows.map(([k, v]) => [k, v]), { header: false });
}

function fieldTable(title, rows) {
  // 与模板 FIELD_HEADERS 一致（含换行说明）
  const headers = [
    '序号',
    '字段中文名称',
    '英文名称',
    '字段类型',
    '必填',
    '校验规则\n（没有明确规则时先限制字符即可，放宽）',
    '备注（如下拉框取值来源、说明等）',
    '是否代码集取值',
    '数据格式样例\n（无特定格式留空）'
  ];
  return p(title, { bold: true }) + table(headers, rows);
}

/**
 * 模板功能按钮格式：
 * 功能按钮——中文（英文名称：En）
 * a. 功能说明（描述、业务的事件交互、备注信息等）：
 * ・描述 / ・业务的事件交互 / ・备注信息
 * b. 原型参考截图：
 * c. 按钮下钻页面（备注说明、原型参考图）：
 */
function funcItem(num, cn, en, desc, interaction, notes, drill, source = '') {
  const title = `${num}、功能按钮——${cn}（英文名称：${en}）${source ? `【来源：${source}】` : ''}`;
  return [
    p(title, { bold: true }),
    p('a. 功能说明（描述、业务的事件交互、备注信息等）：'),
    p(`・描述：${desc}`),
    p(`・业务的事件交互：${interaction}`),
    p(`・备注信息：${notes}`),
    p('b. 原型参考截图：'),
    p('见可交互原型对应界面（中英文截图待补充）。'),
    p('c. 按钮下钻页面（备注说明、原型参考图）：'),
    p(drill),
    p('')
  ].join('');
}

/**
 * 严格按模板菜单块顺序：
 * 菜单介绍 → 页面展示字段 → 支持查询检索 → 数据前后流转（关系说明+1）前置+2）下游）
 * → 业务流关系 → 原型参考链接 → 新增—字段信息表 → 菜单功能清单
 */
function menuBlock(sectionNo, title, status, intro, listFields, searchFields, flowRel, flowPre, flowOut, bizFlow, proto, fieldTables = [], functions = []) {
  let xml = '';
  xml += h(`${sectionNo}${title}（需求确认状态：${status}）`, 4);
  xml += p('菜单介绍', { bold: true });
  xml += p('菜单内容简介', { bold: true });
  xml += p(intro);
  xml += p('页面展示字段信息', { bold: true });
  xml += p(listFields);
  xml += p('支持查询检索的字段信息', { bold: true });
  xml += p(searchFields);
  xml += p('数据前后流转关系（说明、前置条件、下游输出等）', { bold: true });
  xml += p(flowRel);
  xml += p(`1）前置条件`);
  xml += p(flowPre);
  xml += p(`2）下游输出`);
  xml += p(flowOut);
  xml += p('业务流关系（操作流程）', { bold: true });
  xml += p(bizFlow);
  if (proto) {
    xml += p('原型参考链接', { bold: true });
    xml += p(proto);
  }
  if (fieldTables.length) {
    xml += p('新增—字段信息表', { bold: true });
    for (const [ftTitle, ftRows] of fieldTables) xml += fieldTable(ftTitle, ftRows);
  }
  if (functions.length) {
    xml += p('菜单功能清单', { bold: true });
    for (const fn of functions) xml += funcItem(...fn);
  }
  return xml;
}

