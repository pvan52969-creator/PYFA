def parse_rows(md_text: str):
    m = re.search(r"## 2 .*?\n(?:.*\n)*?(\|.+\n\|[-| :]+\n(?:\|.+\n)+)", md_text)
    if not m:
        return []
    lines = [ln for ln in m.group(1).splitlines() if ln.startswith("|")]
    rows = []
    for ln in lines[2:]:
        cells = [c.strip() for c in ln.strip("|").split("|")]
        if len(cells) < 8:
            continue
        rows.append(
            {
                "module": cells[1],
                "obj_type": cells[2],
                "obj_id": cells[3],
                "where": cells[4],
                "type": cells[5],
                "content": cells[6],
                "status": cells[7],
            }
        )
    return rows


