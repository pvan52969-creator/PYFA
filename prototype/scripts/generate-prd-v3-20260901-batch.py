def parse_only_menus() -> set[str] | None:
    """--only 校选课程管理[,开课计划]；未传则生成全部。"""
    if "--only" not in sys.argv:
        return None
    i = sys.argv.index("--only")
    if i + 1 >= len(sys.argv) or sys.argv[i + 1].startswith("--"):
        raise SystemExit("--only 后需跟菜单中文名（逗号分隔）")
    return {x.strip() for x in sys.argv[i + 1].split(",") if x.strip()}


def ensure_writable(path: Path):
    if path.exists() and not ALLOW_OVERWRITE:
        raise SystemExit(f"拒绝覆盖：{path}（如需覆盖请加 --allow-overwrite）")


def ui_name_map(m: dict) -> dict[str, str]:
    return {uid: name for uid, _p, name, *_ in m["uis"]}


def id_cn(uid: str, names: dict[str, str]) -> str:
    if uid in ("—", "-", ""):
        return "—"
    return f"{uid}（{names.get(uid, uid)}）"


def zh_modes(s: str) -> str:
    return (
        s.replace("Query", "查询")
        .replace("Add", "新增")
        .replace("Edit", "编辑")
        .replace("View", "查看")
    )


def ui_kind(uid: str, names: dict[str, str], typ: str | None = None) -> str:
    name = names.get(uid, "")
    last = uid.split("-")[-1] if uid else ""
    if typ == "区块" or last[:1] in "FLTB":
        if "查询" in name or last.startswith("F"):
            return "query"
        if "列表" in name or last.startswith("L"):
            return "list"
        if "工作台" in name or "备注" in name or last.startswith("B"):
            return "workbench"
        if "工具栏" in name or last.startswith("T"):
            return "workbench"
        return "list"
    if last.startswith(("M", "D", "W")) or "-T" in uid[3:]:
        return "form"
    if typ in ("弹窗", "抽屉", "抽屉/展开", "步骤", "页签"):
        return "form"
    return "form"


def pick_one_status(add: str, edit: str, view: str) -> str:
    for s in (edit, view, add):
        if s and s != "—":
            return s
    return "—"


def split_fields(m: dict):
    names = ui_name_map(m)
    typ_by = {uid: typ for uid, _p, _n, typ, *_ in m["uis"]}
    buckets = {"list": [], "query": [], "workbench": [], "form": [], "other": []}
    for row in m["fields"]:
        fid, uid, cn, en, typ, add, edit, view, req, default, rule, src, code, note = row
        kind = ui_kind(uid, names, typ_by.get(uid))
        label = id_cn(uid, names)
        if kind == "list":
            buckets["list"].append(
                (fid, label, cn, en, typ, pick_one_status(add, edit, view), req, default, rule, src, code, note)
            )
        elif kind == "query":
            buckets["query"].append(
                (fid, label, cn, en, typ, pick_one_status(add, edit, view), req, default, rule, src, code, note)
            )
        elif kind == "workbench":
            buckets["workbench"].append(
                (fid, label, cn, en, typ, pick_one_status(add, edit, view), req, default, rule, src, code, note)
            )
        elif kind == "form":
            buckets["form"].append(
                (fid, label, cn, en, typ, add, edit, view, req, default, rule, src, code, note)
            )
        else:
            buckets["other"].append(
                (fid, label, cn, en, typ, pick_one_status(add, edit, view), req, default, rule, src, code, note)
            )
    return buckets


