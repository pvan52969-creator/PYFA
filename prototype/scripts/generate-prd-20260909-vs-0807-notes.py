        f"> **对比基线（开课0807）：** `{baseline}`",
        extra_quote,
        "",
        "## 1 版本信息",
        "",
        "| 项目 | 内容 |",
        "|------|------|",
        f"| 需求文档名称 | 厦大马来分校本科教务系统产品需求文档 — {menu} |",
        f"| 菜单路径 | {menu_path} |",
        f"| 上一有效版 → 本版 | {versions} |",
        f"| 对比基线文件 | {from_file} |",
        f"| 本版文件 | {to_file} |",
